"""
Synthetic Russian marketplace-support preference dataset for DPO (v2).

What changed vs v1
------------------
- Prompt, chosen and rejected are rendered from ONE shared slot set per row,
  so the answer talks about the same item / amount / order as the ticket.
- Grammatical agreement: items carry nom/acc/gen + gender, customers carry a
  gender, so "{item} сломался" / "заказала" etc. agree.
- 12-15 hand-written ticket templates per category (tone ranges from angry
  one-liners to formal complaints), each used at most twice, plus optional
  greetings / tails / order numbers and a noise pipeline (typos on the ЙЦУКЕН
  layout, caps, lost punctuation, chat-style line splits, emoji, rare translit).
- Chosen answers are composed from category-specific fragments (ack / action
  / ask / extra) that are tag-filtered to fit the concrete ticket sub-case.
- Rejected answers are hard negatives: same greeting / acknowledgement /
  request / ticket number / sign-off as the chosen answer, same topic and
  polite tone, but wrong in substance (wrong fact, passive waiting, generic
  instructions, polite deflection, unverified promise, partial resolution,
  answer for a different sub-case, asking for info already given, asking for
  a full card number / SMS code). The report measures how far length and
  bag-of-words shortcuts still separate chosen from rejected.
- No duplicate prompts / chosen / rejected anywhere; near-duplicate prompts
  inside a category are blocked with difflib; AI-sounding phrases are banned.

Output
------
soup_dpo_data/
├── soup_dpo_all.jsonl
├── train.jsonl
├── eval.jsonl
├── soup_dpo_all.csv
└── dataset_report.json

This is a SYNTHETIC dataset and must be described as such in the report.
"""

