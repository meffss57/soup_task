# Exact shares of prompts (not probabilities), applied after generation so the
# duplicate filter cannot skew them. The three groups do not overlap.
QUOTA_NOISE = {"translit": 0.03, "grammar": 0.05, "typos": 0.10, "caps": 0.04}

# Common real spelling/grammar errors in Russian (not keyboard slips):
# -тся/-ться, в течении, merged "не", hyphen words, frequent misspellings.
GRAMMAR_RULES: List[Tuple[str, List[str]]] = [
    (r"\bв течение\b", ["в течении"]),
    (r"\bизвините\b", ["извените"]),
    (r"\bподскажите\b", ["подскажити", "подскажыте"]),
    (r"\bпожалуйста\b", ["пожалуста", "пожалста"]),
    (r"\bздравствуйте\b", ["здраствуйте", "здравствуйти"]),
    (r"\b(\w+)ется\b", ["\\1еться"]),
    (r"\b(\w+)ится\b", ["\\1иться"]),
    (r"\b(\w+)аться\b", ["\\1атся"]),
    (r"\b(\w+)иться\b", ["\\1ится"]),
    (r"\bчто-то\b", ["чтото", "что то"]),
    (r"\bкак-то\b", ["както", "как то"]),
    (r"\bпочему-то\b", ["почемуто", "почему то"]),
    (r"\bкто-нибудь\b", ["кто нибудь", "ктонибудь"]),
    (r"\bне (пришел|пришла|пришли|работает|могу|приходит|приходят|вижу|знаю|нашел|нашла)\b", ["не\\1"]),
    (r"\bничего\b", ["нечего"]),
    (r"\bникто\b", ["ни кто"]),
    (r"\bвообще\b", ["вобще", "ваще"]),
    (r"\bсейчас\b", ["щас", "сечас"]),
    (r"\bчтобы\b", ["что бы"]),
    (r"\bтоже\b", ["то же"]),
    (r"\bоплатил(а?)\b", ["оплотил\\1"]),
    (r"\bоплачивал(а?)\b", ["оплочивал\\1"]),
    (r"\bположили\b", ["ложили"]),
    (r"\bпридет\b", ["прийдет"]),
    (r"\bпрости\b", ["прасти"]),
    (r"\bагентство\b", ["агенство"]),
    (r"\bсегодня\b", ["седня", "сёдня"]),
    (r"\bзаказывал(а?)\b", ["закозывал\\1"]),
    (r"\bотменил(а?)\b", ["отминил\\1"]),
    (r"\bкомпенсирует\b", ["компенсирут"]),
]


def grammar_candidates(text: str) -> List[int]:
    return [k for k, (pat, _) in enumerate(GRAMMAR_RULES) if re.search(pat, text, flags=re.IGNORECASE)]


def inject_grammar(text: str, rng: random.Random) -> str:
    rules = grammar_candidates(text)
    for k in rng.sample(rules, k=min(len(rules), rng.randint(1, 2))):
        pat, repls = GRAMMAR_RULES[k]
        repl = rng.choice(repls)

        def sub(m: re.Match) -> str:
            out = m.expand(repl)
            return out[0].upper() + out[1:] if m.group(0)[0].isupper() else out

        new = re.sub(pat, sub, text, count=1, flags=re.IGNORECASE)
        if new != text:
            text = new
    return text


def apply_caps(text: str, rng: random.Random) -> str:
    if len(text) < 60 and rng.random() < 0.5:
        return text.upper()
    words = text.split(" ")
    n = rng.randint(2, 4)
    s = rng.randint(0, max(0, len(words) - n))
    words[s:s + n] = [w.upper() for w in words[s:s + n]]
    return " ".join(words)


def apply_quota_noise(rows: List[dict], rng: random.Random) -> None:
    n = len(rows)
    counts = {k: round(v * n) for k, v in QUOTA_NOISE.items()}
    order = list(range(n))
    rng.shuffle(order)
    # translit only on shorter messages, like people typing quickly on a phone
    short = [i for i in order if len(rows[i]["prompt"]) < 120]
    picked = {"translit": short[:counts["translit"]]}
    taken = set(picked["translit"])
    # grammar errors only where a real rule applies (and actually changes the text)
    gram = [i for i in order if i not in taken
            and inject_grammar(rows[i]["prompt"], random.Random(i)) != rows[i]["prompt"]]
    picked["grammar"] = gram[:counts["grammar"]]
    taken |= set(picked["grammar"])
    rest = [i for i in order if i not in taken]
    picked["typos"] = rest[:counts["typos"]]
    picked["caps"] = rest[counts["typos"]:counts["typos"] + counts["caps"]]
    for op, idxs in picked.items():
        for i in idxs:
            r = rows[i]
            if op == "translit":
                r["prompt"] = to_translit(r["prompt"].lower())
            elif op == "grammar":
                before = r["prompt"]
                r["prompt"] = inject_grammar(before, rng)
                while r["prompt"] == before:
                    r["prompt"] = inject_grammar(before, rng)
            elif op == "typos":
                r["prompt"] = inject_typos(r["prompt"], rng)
            else:
                r["prompt"] = apply_caps(r["prompt"], rng)
            r["metadata"]["noise"].append(op)
            ops = [x for x in r["metadata"]["noise"] if x not in ("greeting", "tail", "order_number", "story")]
            r["noise_type"] = "+".join(ops) or "clean"


def normalize(text: str) -> str:
    text = text.lower().replace("ё", "е")
    text = re.sub(r"[^\w\s]", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def least_used(options: List, counter: Counter, rng: random.Random, key=lambda x: x):
    """Pick uniformly among the least-used options."""
    if not options:
        raise ValueError("no options")
    m = min(counter[key(o)] for o in options)
    return rng.choice([o for o in options if counter[key(o)] == m])


@dataclass
class CategoryState:
    name: str
    spec: dict
    prompts: List[Fragment] = field(default_factory=list)
    ack: List[Fragment] = field(default_factory=list)
    action: List[Fragment] = field(default_factory=list)
    ask: List[Fragment] = field(default_factory=list)
    extra: List[Fragment] = field(default_factory=list)
    rejected: List[Tuple[str, Fragment]] = field(default_factory=list)
    usage: Counter = field(default_factory=Counter)


def load_categories() -> Dict[str, CategoryState]:
    states = {}
    for name, spec in CATEGORIES.items():
        st = CategoryState(name, spec)
        st.prompts = [parse_fragment(p) for p in spec["prompts"]]
        st.ack = [parse_fragment(p) for p in spec["ack"]]
        st.action = [parse_fragment(p) for p in spec["action"]]
        st.ask = [parse_fragment(p) for p in spec["ask"]]
        st.extra = [parse_fragment(p) for p in spec["extra"]]
        st.rejected = [(t, parse_fragment(p)) for t, p in spec["rejected"]]
        for t, _ in st.rejected:
            assert t in REJECTED_RATIONALE, t
        # Every ticket template needs at least one fitting action / ask / rejected.
        for p in st.prompts:
            tags = set(p.inc)
            for pool_name in ("action", "ask"):
                if not any(f.fits(tags) for f in getattr(st, pool_name)):
                    raise ValueError(f"{name}: no {pool_name} fits prompt {p.text!r}")
            if not any(f.fits(tags) for _, f in st.rejected):
                raise ValueError(f"{name}: no rejected fits prompt {p.text!r}")
        if len(st.prompts) * MAX_TEMPLATE_USES < PAIRS_PER_CATEGORY:
            raise ValueError(f"{name}: not enough prompt templates")
        states[name] = st
    return states


def pick_template(st: CategoryState, rng: random.Random) -> Fragment:
    options = [p for p in st.prompts if st.usage[("prompt", p.text)] < MAX_TEMPLATE_USES]
    return least_used(options, st.usage, rng, key=lambda p: ("prompt", p.text))


def pick_capped(pool: List[str], usage: Counter, rng: random.Random) -> Optional[str]:
    free = [x for x in pool if usage[x] < MAX_EXTRA_USES]
    return least_used(free, usage, rng) if free else None


def build_prompt(st: CategoryState, tpl: Fragment, slots: Dict[str, str], info: dict,
                 rng: random.Random, extra_usage: Counter) -> Tuple[str, List[str], bool, List[str]]:
    body = render(tpl.text, slots)
    extras: List[str] = []
    used_extras: List[str] = []

    has_order = False
    if st.spec["order_ok"] and rng.random() < 0.3:
        has_order = True
        order_bit = rng.choice(["заказ {order}", "номер заказа {order}", "№{order}", "заказ №{order}"]).format(**slots)
        if rng.random() < 0.4:
            body = f"{order_bit} {body}"
        elif body[-1] in "?!":
            body = f"{body} {order_bit}"
        else:
            body = f"{body.rstrip('.')}. {order_bit}"
        extras.append("order_number")

    story_key = pick_capped(PROMPT_STORIES, extra_usage, rng) if rng.random() < 0.2 else None
    if story_key:
        used_extras.append(story_key)
        story = render(story_key, slots)
        if rng.random() < 0.5:
            body = f"{story}. {body}"
        else:
            body = f"{body.rstrip('.')}{'' if body[-1] in '?!' else '.'} {story[0].upper() + story[1:]}"
        extras.append("story")
    if rng.random() < 0.16:
        body = f"{rng.choice(PROMPT_HEADS)} {body[0].lower() + body[1:] if rng.random() < 0.5 else body}"
        extras.append("greeting")
    tail_key = pick_capped(PROMPT_TAILS, extra_usage, rng) if rng.random() < 0.25 else None
    if tail_key:
        used_extras.append(tail_key)
        sep = rng.choice([". ", ", ", " ", "\n"])
        body = body.rstrip(".") + sep + render(tail_key, slots)
        extras.append("tail")

    body, noise = apply_noise(tidy(body), rng)
    return body, extras + noise, has_order, used_extras


def compose_chosen(st: CategoryState, tags: Set[str], slots: Dict[str, str],
                   rng: random.Random) -> Tuple[str, Dict[str, str]]:
    def pick(pool: List[Fragment], kind: str) -> Fragment:
        fitting = [f for f in pool if f.fits(tags)]
        return least_used(fitting, st.usage, rng, key=lambda f: (kind, f.text))

    parts: List[str] = []
    used: Dict[str, str] = {}
    greeting_tpl = rng.choice(GREETINGS)
    if greeting_tpl:
        parts.append(render(greeting_tpl, slots))
    if rng.random() < 0.4:
        f = pick(st.ack, "ack")
        parts.append(render(f.pick(rng), slots))
        used["ack"] = f.text
    action = pick(st.action, "action")
    ask = pick(st.ask, "ask")
    used["action"], used["ask"] = action.text, ask.text
    parts.extend([render(action.pick(rng), slots), render(ask.pick(rng), slots)])
    extra = rng.choice(st.extra)
    if extra.text and rng.random() < 0.45:
        parts.append(render(extra.pick(rng), slots))
    if "служба поддержки" not in greeting_tpl:
        signoff = render(rng.choice(SIGNOFFS), slots)
        if signoff:
            parts.append(signoff)
    return tidy(" ".join(parts)), used


# Shared pools in bad answers are rotated evenly (least-used first) instead of
# sampled at random, so no boilerplate sentence dominates the dataset.
POOL_USAGE: Counter = Counter()


def balanced(pool: List[str], k: int, rng: random.Random) -> List[str]:
    out: List[str] = []
    for _ in range(min(k, len(pool))):
        x = least_used([p for p in pool if p not in out], POOL_USAGE, rng)
        POOL_USAGE[x] += 1
        out.append(x)
    return out


REDUNDANT_QUESTIONS = [
    "Уточните, пожалуйста, номер заказа, чтобы мы могли проверить информацию.",
    "Пришлите номер заказа, без него мы не можем посмотреть детали.",
    "Для проверки нужен номер заказа, напишите его, пожалуйста.",
    "Подскажите номер заказа и опишите ситуацию подробнее, тогда сможем помочь.",
]


def compose_rejected(st: CategoryState, tags: Set[str], slots: Dict[str, str], rng: random.Random,
                     states: Dict[str, CategoryState]) -> Tuple[str, str, str, Optional[str]]:
    """Hard negative: same greeting / acknowledgement / ticket number / sign-off
    machinery as the chosen answer, same topic and tone, but wrong in substance.
    Returns (text, failure_type, source, specific_fragment_text)."""
    has_order = slots["ask_order"] == ""
    # Chosen actions written for a *different* sub-case of this category.
    wrong_sub = [f for f in st.action if f.inc and tags and not (f.inc & tags)] if tags else []

    kinds, weights = ["specific"], [75]
    if wrong_sub:
        kinds.append("wrong_subcase")
        weights.append(15)
    if has_order:
        kinds.append("redundant")
        weights.append(10)
    kind = rng.choices(kinds, weights=weights)[0]

    parts: List[str] = []
    greeting_tpl = rng.choice(GREETINGS)
    if greeting_tpl:
        parts.append(render(greeting_tpl, slots))
    if rng.random() < 0.4:
        parts.append(render(rng.choice(st.ack).pick(rng), slots))

    frag_text = None
    if kind == "specific":
        fitting = [(t, f) for t, f in st.rejected if f.fits(tags)]
        ftype, frag = least_used(fitting, st.usage, rng, key=lambda x: ("rej", x[1].text))
        parts.append(render(frag.pick(rng), slots))
        frag_text, src = frag.text, "specific"
    elif kind == "wrong_subcase":
        frag = least_used(wrong_sub, st.usage, rng, key=lambda f: ("rej_sub", f.text))
        parts.append(render(frag.pick(rng), slots))
        ftype, src = "wrong_subcase", "chosen_fragment_other_subcase"
        st.usage[("rej_sub", frag.text)] += 1
    else:
        parts.append(balanced(REDUNDANT_QUESTIONS, 1, rng)[0])
        ftype, src = "redundant_question", "redundant"

    # Wrong answers from real operators usually still end with a normal
    # request ("send a screenshot..."); reuse the category's request sentences
    # so vocabulary and length do not give the label away.
    if kind != "redundant" and rng.random() < 0.75:
        asks = [f for f in st.ask if f.fits(tags)]
        parts.append(render(rng.choice(asks).pick(rng), slots))
    extra = rng.choice(st.extra)
    if extra.text and rng.random() < 0.45:
        parts.append(render(extra.pick(rng), slots))
    if "служба поддержки" not in greeting_tpl:
        signoff = render(rng.choice(SIGNOFFS), slots)
        if signoff:
            parts.append(signoff)
    return tidy(" ".join(parts)), ftype, src, frag_text


def too_similar(text: str, others: List[str], ratio: float) -> bool:
    """Symmetric check: difflib's ratio can depend on argument order."""
    n = normalize(text)
    for o in others:
        sm = difflib.SequenceMatcher(None, n, o, autojunk=False)
        if sm.real_quick_ratio() < ratio or sm.quick_ratio() < ratio:
            continue
        if sm.ratio() >= ratio or difflib.SequenceMatcher(None, o, n, autojunk=False).ratio() >= ratio:
            return True
    return False


def generate_dataset(seed: int = SEED) -> List[dict]:
    rng = random.Random(seed)
    states = load_categories()
    rows: List[dict] = []
    seen_prompt: Set[str] = set()
    seen_chosen: Set[str] = set()
    seen_rejected: Set[str] = set()
    extra_usage: Counter = Counter()
    POOL_USAGE.clear()

    for name, st in states.items():
        cat_prompts: List[str] = []
        cat_chosen: List[str] = []
        produced = 0
        attempts = 0
        while produced < PAIRS_PER_CATEGORY:
            attempts += 1
            if attempts > 5000:
                raise RuntimeError(f"{name}: could not produce {PAIRS_PER_CATEGORY} unique rows")

            tpl = pick_template(st, rng)
            tags = set(tpl.inc)
            slots, info = build_slots(st.spec, tags, rng)
            prompt, noise, has_order, used_extras = build_prompt(st, tpl, slots, info, rng, extra_usage)
            np_ = normalize(prompt)
            if np_ in seen_prompt or too_similar(prompt, cat_prompts, PROMPT_NEAR_DUP_RATIO):
                continue

            slots["ask_order"] = "" if has_order else "номер заказа и "
            slots["order_ref"] = f" по заказу {slots['order']}" if has_order else ""

            chosen, used = None, {}
            for _ in range(40):
                cand, used_c = compose_chosen(st, tags, slots, rng)
                if normalize(cand) not in seen_chosen and not too_similar(cand, cat_chosen, CHOSEN_NEAR_DUP_RATIO):
                    chosen, used = cand, used_c
                    break
            if chosen is None:
                continue

            rejected = None
            for _ in range(60):
                cand, ftype, src, frag_text = compose_rejected(st, tags, slots, rng, states)
                if normalize(cand) not in seen_rejected:
                    rejected = cand
                    break
            if rejected is None:
                continue

            st.usage[("prompt", tpl.text)] += 1
            extra_usage.update(used_extras)
            for k, v in used.items():
                st.usage[(k, v)] += 1
            if frag_text:
                st.usage[("rej", frag_text)] += 1
            seen_prompt.add(np_)
            seen_chosen.add(normalize(chosen))
            seen_rejected.add(normalize(rejected))
            cat_prompts.append(np_)
            cat_chosen.append(normalize(chosen))

            rows.append({
                "id": "",
                "prompt": prompt,
                "chosen": chosen,
                "rejected": rejected,
                "chosen_rationale": st.spec["chosen_rationale"],
                "rejected_rationale": REJECTED_RATIONALE[ftype],
                "metadata": {
                    "issue_type": name,
                    "tier": st.spec["tier"],
                    "failure_mode": ftype,
                    "rejected_source": src,
                    "prompt_template": st.prompts.index(tpl),
                    "prompt_tags": sorted(tpl.inc),
                    "noise": noise,
                    "customer_gender": info["user_gender"],
                    "has_order_number": has_order,
                    "language": "ru",
                    "synthetic": True,
                },
                "category": name,
                "noise_type": "+".join(n for n in noise if n not in ("greeting", "tail", "order_number", "story")) or "clean",
                "source": "synthetic",
            })
            produced += 1

    apply_quota_noise(rows, random.Random(seed + 1))
    rng.shuffle(rows)
    for i, row in enumerate(rows, start=1):
        row["id"] = f"soup-{i:04d}"
    return rows


