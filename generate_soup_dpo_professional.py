REQUIRED_FIELDS = ["id", "prompt", "chosen", "rejected", "chosen_rationale", "rejected_rationale",
                   "metadata", "category", "noise_type", "source"]


def validate_row(row: dict) -> List[str]:
    errors = [f"missing_{f}" for f in REQUIRED_FIELDS if not row.get(f)]
    for f in ("prompt", "chosen", "rejected"):
        t = row.get(f, "")
        if re.search(r"[{}]", t):
            errors.append(f"unfilled_slot_in_{f}")
        low = t.lower()
        for m in AI_MARKERS:
            if m in low:
                errors.append(f"ai_marker_in_{f}:{m}")
    if normalize(row["chosen"]) == normalize(row["rejected"]):
        errors.append("chosen_equals_rejected")
    if len(row["prompt"].strip()) < 10:
        errors.append("prompt_too_short")
    if len(row["chosen"]) < 80:
        errors.append("chosen_too_short")
    if len(row["rejected"]) < 12:
        errors.append("rejected_too_short")
    return errors


def duplicates(rows: List[dict], field_name: str) -> List[int]:
    seen, dup = set(), []
    for i, r in enumerate(rows):
        n = normalize(r[field_name])
        if n in seen:
            dup.append(i)
        seen.add(n)
    return dup


def near_duplicate_prompts(rows: List[dict], ratio: float) -> int:
    by_cat = defaultdict(list)
    for r in rows:
        by_cat[r["category"]].append(normalize(r["prompt"]))
    count = 0
    for prompts in by_cat.values():
        for i in range(len(prompts)):
            if too_similar(prompts[i], prompts[:i], ratio):
                count += 1
    return count


def validate_dataset(rows: List[dict]) -> dict:
    row_errors = []
    for i, r in enumerate(rows):
        e = validate_row(r)
        if e:
            row_errors.append({"row": i, "id": r["id"], "errors": e})
    return {
        "num_rows": len(rows),
        "row_errors": row_errors,
        "duplicate_prompts": len(duplicates(rows, "prompt")),
        "duplicate_chosen": len(duplicates(rows, "chosen")),
        "duplicate_rejected": len(duplicates(rows, "rejected")),
        "near_duplicate_prompts_same_category": near_duplicate_prompts(rows, PROMPT_NEAR_DUP_RATIO),
    }


