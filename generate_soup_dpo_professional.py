@dataclass(frozen=True)
class Fragment:
    text: str
    inc: frozenset = frozenset()
    exc: frozenset = frozenset()
    variants: Tuple[str, ...] = ()

    def pick(self, rng: random.Random) -> str:
        return rng.choice(self.variants) if self.variants else self.text

    def fits(self, tags: Set[str]) -> bool:
        if self.inc and not (self.inc & tags):
            return False
        return not (self.exc & tags)


def parse_fragment(raw: str) -> Fragment:
    inc = exc = frozenset()
    text = raw
    if raw.startswith("@"):
        head, text = raw[1:].split("|", 1)
        tags = [t.strip() for t in head.split(",") if t.strip()]
        inc = frozenset(t for t in tags if not t.startswith("-"))
        exc = frozenset(t[1:] for t in tags if t.startswith("-"))
    variants = (text, *PARAPHRASES.get(text, ()))
    return Fragment(text, inc, exc, variants)


def fmt_thousands(n: int) -> str:
    return f"{n:,}".replace(",", " ")


def fmt_date(d: dt.date) -> str:
    return f"{d.day} {MONTHS_GEN[d.month]}"


def messy_date(d: dt.date, rng: random.Random) -> str:
    return rng.choice([fmt_date(d), f"{d.day:02d}.{d.month:02d}", f"{d.day}го", f"{d.day}.{d.month:02d}"])


