def stratified_split(rows: List[dict], eval_size: int, seed: int) -> Tuple[List[dict], List[dict]]:
    """5 eval rows per category. Eval prefers prompt templates that appear only
    once in the category, so eval tickets are not paraphrases of train tickets."""
    rng = random.Random(seed)
    by_cat: Dict[str, List[dict]] = defaultdict(list)
    for r in rows:
        by_cat[r["category"]].append(r)
    per_cat = eval_size // len(by_cat)
    train, evl = [], []
    for cat in sorted(by_cat):
        examples = by_cat[cat][:]
        rng.shuffle(examples)
        tpl_count = Counter(r["metadata"]["prompt_template"] for r in examples)
        examples.sort(key=lambda r: tpl_count[r["metadata"]["prompt_template"]])
        eval_ids: List[str] = []
        used_tpl: Set[int] = set()
        for r in examples:
            t = r["metadata"]["prompt_template"]
            if len(eval_ids) < per_cat and t not in used_tpl:
                eval_ids.append(r["id"])
                used_tpl.add(t)
        eval_set = set(eval_ids)
        evl.extend(r for r in examples if r["id"] in eval_set)
        train.extend(r for r in examples if r["id"] not in eval_set)
    rng.shuffle(train)
    rng.shuffle(evl)
    return train, evl


def write_jsonl(rows: List[dict], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")


def write_csv(rows: List[dict], path: Path) -> None:
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=REQUIRED_FIELDS)
        w.writeheader()
        for r in rows:
            out = {k: r[k] for k in REQUIRED_FIELDS}
            out["metadata"] = json.dumps(r["metadata"], ensure_ascii=False)
            w.writerow(out)


def length_stats(values: List[int]) -> dict:
    values = sorted(values)
    return {"min": values[0], "max": values[-1], "mean": round(sum(values) / len(values), 1),
            "median": values[len(values) // 2]}


def shortcut_baselines(rows: List[dict]) -> dict:
    """How well do trivial cues separate chosen from rejected?
    ~0.5 means the cue is useless, ~1.0 means a model can win without reading the ticket."""
    out = {"length_only_pair_accuracy": round(
        sum(len(r["chosen"]) > len(r["rejected"]) for r in rows) / len(rows), 3)}
    try:
        from sklearn.feature_extraction.text import TfidfVectorizer
        from sklearn.linear_model import LogisticRegression
        from sklearn.model_selection import GroupKFold
    except ImportError:
        out["bag_of_words"] = "sklearn not installed"
        return out
    texts = [r["chosen"] for r in rows] + [r["rejected"] for r in rows]
    labels = [1] * len(rows) + [0] * len(rows)
    groups = list(range(len(rows))) * 2
    pair_correct, single_correct = 0, 0
    for tr, te in GroupKFold(n_splits=5).split(texts, labels, groups):
        vec = TfidfVectorizer(ngram_range=(1, 2), min_df=2)
        X = vec.fit_transform([texts[i] for i in tr])
        clf = LogisticRegression(max_iter=2000).fit(X, [labels[i] for i in tr])
        scores = clf.decision_function(vec.transform([texts[i] for i in te]))
        by_pair = {}
        for i, sc in zip(te, scores):
            single_correct += int((sc > 0) == bool(labels[i]))
            by_pair.setdefault(groups[i], {})[labels[i]] = sc
        pair_correct += sum(v[1] > v[0] for v in by_pair.values())
    out["bag_of_words_single_response_accuracy"] = round(single_correct / len(texts), 3)
    out["bag_of_words_pair_accuracy"] = round(pair_correct / len(rows), 3)
    return out


def build_report(rows, train, evl, validation) -> dict:
    rej_longer = sum(1 for r in rows if len(r["rejected"]) > len(r["chosen"]))
    noise_ops = Counter(op for r in rows for op in r["metadata"]["noise"])
    tpl_train = {(r["category"], r["metadata"]["prompt_template"]) for r in train}
    tpl_eval = {(r["category"], r["metadata"]["prompt_template"]) for r in evl}
    return {
        "dataset": {
            "name": "soup_synthetic_russian_support_dpo_v2",
            "synthetic": True,
            "language": "ru",
            "total_pairs": len(rows),
            "train_pairs": len(train),
            "eval_pairs": len(evl),
            "num_categories": NUM_CATEGORIES,
            "pairs_per_category": PAIRS_PER_CATEGORY,
            "seed": SEED,
        },
        "schema": REQUIRED_FIELDS,
        "category_distribution": dict(sorted(Counter(r["category"] for r in rows).items())),
        "rejected_failure_mode_distribution": dict(Counter(r["metadata"]["failure_mode"] for r in rows).most_common()),
        "noise_op_counts": dict(noise_ops.most_common()),
        "noise_type_distribution": dict(Counter(r["noise_type"] for r in rows).most_common()),
        "prompts_with_order_number": sum(r["metadata"]["has_order_number"] for r in rows),
        "length_chars": {
            "prompt": length_stats([len(r["prompt"]) for r in rows]),
            "chosen": length_stats([len(r["chosen"]) for r in rows]),
            "rejected": length_stats([len(r["rejected"]) for r in rows]),
            "share_rejected_longer_than_chosen": round(rej_longer / len(rows), 3),
        },
        "known_biases": [
            "Chosen answers are usually longer than rejected ones; a length-only reward would already prefer chosen in most pairs. Rule this out before crediting DPO reward margins to learning.",
            "Rejected answers are hard negatives (polite, on-topic, same structure) that are wrong in substance; see shortcut_baselines for how far surface cues still separate them.",
            "Some prompt templates are used twice inside a category (different slots and noise); eval rows use templates that are, where possible, unique within the category.",
        ],
        "shortcut_baselines": shortcut_baselines(rows),
        "eval_templates_also_in_train": len(tpl_train & tpl_eval),
        "validation": validation,
    }


def main() -> None:
    print("=" * 72)
    print("SOUP SYNTHETIC RUSSIAN DPO DATASET GENERATOR v2")
    print("=" * 72)

    rows = generate_dataset(SEED)
    validation = validate_dataset(rows)

    problems = (validation["row_errors"] or validation["duplicate_prompts"] or validation["duplicate_chosen"]
                or validation["duplicate_rejected"] or validation["near_duplicate_prompts_same_category"])
    if problems:
        print(json.dumps(validation, ensure_ascii=False, indent=2)[:4000])
        raise RuntimeError("Dataset validation failed.")

    counts = Counter(r["category"] for r in rows)
    if len(rows) != TOTAL_PAIRS or any(v != PAIRS_PER_CATEGORY for v in counts.values()):
        raise RuntimeError(f"Bad balance: {counts}")

    train, evl = stratified_split(rows, EVAL_SIZE, SEED)
    if len(train) != TRAIN_SIZE or len(evl) != EVAL_SIZE:
        raise RuntimeError(f"Bad split sizes {len(train)}/{len(evl)}")
    if {normalize(r["prompt"]) for r in train} & {normalize(r["prompt"]) for r in evl}:
        raise RuntimeError("Train/eval prompt leakage")

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    write_jsonl(rows, OUTPUT_DIR / "soup_dpo_all.jsonl")
    write_jsonl(train, OUTPUT_DIR / "train.jsonl")
    write_jsonl(evl, OUTPUT_DIR / "eval.jsonl")
    write_csv(rows, OUTPUT_DIR / "soup_dpo_all.csv")
    report = build_report(rows, train, evl, validation)
    (OUTPUT_DIR / "dataset_report.json").write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"Total pairs: {len(rows)}  train: {len(train)}  eval: {len(evl)}  categories: {len(counts)}")
    print("Rejected failure modes:", json.dumps(report["rejected_failure_mode_distribution"], ensure_ascii=False))
    print("Length (chars):", json.dumps(report["length_chars"], ensure_ascii=False))
    print("Eval templates also used in train:", report["eval_templates_also_in_train"])
    print("Shortcut baselines:", json.dumps(report["shortcut_baselines"]))
    print("Validation: PASSED (no duplicates, no near-duplicate prompts, no AI markers, no unfilled slots)")
    print("\nExample record:")
    print(json.dumps(rows[0], ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
